static void LCD_SPI_WriteByte(uint8_t value)
{
    DL_SPI_transmitData8(SPI_LCD_INST, value);
    while (DL_SPI_isBusy(SPI_LCD_INST)) {
    }
}

static void LCD_SPI_WriteCommand(uint8_t command)
{
    LCD_CS_LOW();
    LCD_DC_LOW();
    LCD_SPI_WriteByte(command);
    LCD_CS_HIGH();
}

static void LCD_SPI_WriteData(const uint8_t *data, uint8_t length)
{
    uint8_t index;

    LCD_CS_LOW();
    LCD_DC_HIGH();
    for (index = 0U; index < length; ++index) {
        LCD_SPI_WriteByte(data[index]);
    }
    LCD_CS_HIGH();
}

static void LCD_SPI_CommandData(uint8_t command,
                                const uint8_t *data, uint8_t length)
{
    LCD_SPI_WriteCommand(command);
    if ((data != NULL) && (length > 0U)) {
        LCD_SPI_WriteData(data, length);
    }
}

static void LCD_SPI_SetWindow(uint16_t x1, uint16_t y1,
                              uint16_t x2, uint16_t y2)
{
    uint8_t data[4];

    x1 += LCD_X_OFFSET;
    x2 += LCD_X_OFFSET;
    y1 += LCD_Y_OFFSET;
    y2 += LCD_Y_OFFSET;

    data[0] = (uint8_t)(x1 >> 8U);
    data[1] = (uint8_t)x1;
    data[2] = (uint8_t)(x2 >> 8U);
    data[3] = (uint8_t)x2;
    LCD_SPI_CommandData(0x2AU, data, 4U);

    data[0] = (uint8_t)(y1 >> 8U);
    data[1] = (uint8_t)y1;
    data[2] = (uint8_t)(y2 >> 8U);
    data[3] = (uint8_t)y2;
    LCD_SPI_CommandData(0x2BU, data, 4U);
    LCD_SPI_WriteCommand(0x2CU);
}

static void LCD_SPI_BeginPixels(void)
{
    LCD_CS_LOW();
    LCD_DC_HIGH();
}

static void LCD_SPI_WriteColor(uint16_t color)
{
    LCD_SPI_WriteByte((uint8_t)(color >> 8U));
    LCD_SPI_WriteByte((uint8_t)color);
}

static void LCD_SPI_EndPixels(void)
{
    LCD_CS_HIGH();
}

void LCD_SPI_Init(void)
{
    static const uint8_t frame1[] = {0x05U, 0x3CU, 0x3CU};
    static const uint8_t frame3[] = {0x05U, 0x3CU, 0x3CU,
                                     0x05U, 0x3CU, 0x3CU};
    static const uint8_t power0[] = {0x28U, 0x08U, 0x04U};
    static const uint8_t power2[] = {0x0DU, 0x00U};
    static const uint8_t power3[] = {0x8DU, 0x2AU};
    static const uint8_t power4[] = {0x8DU, 0xEEU};
    static const uint8_t gamma_p[] = {
        0x04U,0x22U,0x07U,0x0AU,0x2EU,0x30U,0x25U,0x2AU,
        0x28U,0x26U,0x2EU,0x3AU,0x00U,0x01U,0x03U,0x13U};
    static const uint8_t gamma_n[] = {
        0x04U,0x16U,0x06U,0x0DU,0x2DU,0x26U,0x23U,0x27U,
        0x27U,0x25U,0x2DU,0x3BU,0x00U,0x01U,0x04U,0x13U};
    uint8_t value;

    LCD_CS_HIGH();
    LCD_DC_HIGH();
    LCD_BLK_LOW();
    LCD_RES_LOW();
    mspm0_delay_ms(100U);
    LCD_RES_HIGH();
    mspm0_delay_ms(100U);
    LCD_BLK_HIGH();
    mspm0_delay_ms(100U);

    LCD_SPI_WriteCommand(0x11U);
    mspm0_delay_ms(120U);
    LCD_SPI_CommandData(0xB1U, frame1, sizeof(frame1));
    LCD_SPI_CommandData(0xB2U, frame1, sizeof(frame1));
    LCD_SPI_CommandData(0xB3U, frame3, sizeof(frame3));
    value = 0x03U;
    LCD_SPI_CommandData(0xB4U, &value, 1U);
    LCD_SPI_CommandData(0xC0U, power0, sizeof(power0));
    value = 0xC0U;
    LCD_SPI_CommandData(0xC1U, &value, 1U);
    LCD_SPI_CommandData(0xC2U, power2, sizeof(power2));
    LCD_SPI_CommandData(0xC3U, power3, sizeof(power3));
    LCD_SPI_CommandData(0xC4U, power4, sizeof(power4));
    value = 0x1AU;
    LCD_SPI_CommandData(0xC5U, &value, 1U);
    value = 0xC0U;
    LCD_SPI_CommandData(0x36U, &value, 1U);
    LCD_SPI_CommandData(0xE0U, gamma_p, sizeof(gamma_p));
    LCD_SPI_CommandData(0xE1U, gamma_n, sizeof(gamma_n));
    value = 0x05U;
    LCD_SPI_CommandData(0x3AU, &value, 1U);
    LCD_SPI_WriteCommand(0x29U);
}

void LCD_SPI_Fill(uint16_t color)
{
    uint32_t remaining = (uint32_t)LCD_SPI_WIDTH * LCD_SPI_HEIGHT;

    LCD_SPI_SetWindow(0U, 0U, LCD_SPI_WIDTH - 1U, LCD_SPI_HEIGHT - 1U);
    LCD_SPI_BeginPixels();
    while (remaining-- > 0U) {
        LCD_SPI_WriteColor(color);
    }
    LCD_SPI_EndPixels();
}

static void LCD_SPI_DrawChar(uint16_t x, uint16_t y, char character,
                             uint16_t foreground, uint16_t background)
{
    uint8_t row;
    uint8_t column;
    const uint8_t *glyph;

    if ((character < ' ') || (character > '~') ||
        (x + 6U > LCD_SPI_WIDTH) || (y + 8U > LCD_SPI_HEIGHT)) {
        return;
    }

    glyph = g_font5x7[(uint8_t)character - (uint8_t)' '];
    LCD_SPI_SetWindow(x, y, x + 5U, y + 7U);
    LCD_SPI_BeginPixels();
    for (row = 0U; row < 8U; ++row) {
        for (column = 0U; column < 6U; ++column) {
            uint16_t color = background;
            if ((column < 5U) && ((glyph[column] & (1U << row)) != 0U)) {
                color = foreground;
            }
            LCD_SPI_WriteColor(color);
        }
    }
    LCD_SPI_EndPixels();
}

void LCD_SPI_DrawString(uint16_t x, uint16_t y, const char *text,
                        uint16_t foreground, uint16_t background)
{
    if (text == NULL) {
        return;
    }

    while ((*text != '\0') && (x + 6U <= LCD_SPI_WIDTH)) {
        LCD_SPI_DrawChar(x, y, *text++, foreground, background);
        x += 6U;
    }
}
